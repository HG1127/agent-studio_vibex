import test from "node:test"
import assert from "node:assert/strict"
import {readFileSync} from "node:fs"
import path from "node:path"
import {fileURLToPath} from "node:url"

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),"../../..")
const read=file=>readFileSync(path.join(root,file),"utf8")
const nginx=read("ops/templates/agentstudio-pg18-lan-https-7443.conf.example")
const unit=read("ops/templates/agentstudio-pg18-native.service.example")
const audit=read("ops/baota-pg18-lan-https-audit.sh")
const portal=read("ops/native-lan-pilot/www/app.js")
const html=read("ops/native-lan-pilot/www/index.html")

test("uninstalled HTTPS template cannot modify original BaoTa panel or proxy externally",()=>{
  assert.match(nginx,/listen 192\.168\.1\.133:7443 ssl;/)
  assert.match(nginx,/server_name 192\.168\.1\.133;/)
  assert.match(nginx,/subjectAltName=IP:192\.168\.1\.133/)
  assert.match(nginx,/allow 192\.168\.1\.0\/24;/)
  assert.match(nginx,/deny all;/)
  assert.match(nginx,/location = \/api\/native-auth\/employees \{ return 403; \}/)
  assert.match(nginx,/limit_except GET \{ deny all; \}/)
  assert.match(nginx,/location \^~ \/api\/v2\/runs \{ return 404; \}/)
  assert.match(nginx,/client_max_body_size 16k;/)
  assert.match(nginx,/proxy_cache off;/)
  assert.match(nginx,/access_log off;/)
  assert.match(nginx,/frame-ancestors 'none'/)
  assert.match(nginx,/script-src 'self'/)
  const targets=[...nginx.matchAll(/proxy_pass\s+([^;\s]+);/g)].map(m=>m[1])
  assert.equal(targets.length,2)
  assert.ok(targets.every(x=>x==="http://127.0.0.1:7403"))
  const active=nginx.split("\n").filter(line=>!line.trim().startsWith("#")).join("\n")
  assert.doesNotMatch(active,/^\s*add_header\s+Access-Control-Allow-Origin/im)
  assert.doesNotMatch(active,/__pb|proxy_pass.*(?:192\.168|0\.0\.0\.0)/i)
  assert.doesNotMatch(nginx,/\blisten\s+(?:80|82|443)\b/)
})
test("systemd test service uses non-root private credentials and has no auto-enable",()=>{
  assert.match(unit,/DynamicUser=yes/)
  assert.match(unit,/User=agentstudio-native/)
  assert.match(unit,/LoadCredential=api\.secret:\/root\/\.agentstudio-pg18-secrets\/api\.secret/)
  assert.match(unit,/LoadCredential=native-auth\.secret:\/root\/\.agentstudio-pg18-secrets\/native-auth\.secret/)
  assert.match(unit,/Environment=AGENT_STUDIO_PG_PASSWORD_FILE=\/run\/credentials\/agentstudio-pg18-native\.service\/api\.secret/)
  assert.match(unit,/Environment=AGENT_STUDIO_PG_NATIVE_AUTH_PASSWORD_FILE=\/run\/credentials\/agentstudio-pg18-native\.service\/native-auth\.secret/)
  assert.doesNotMatch(unit,/^Environment=[^\n]*%d\//m)
  assert.match(unit,/Environment=AGENT_STUDIO_INTERNAL_APP_ORIGIN=https:\/\/192\.168\.1\.133:7443/)
  assert.match(unit,/ExecStart=\/opt\/agentstudio-node24\/bin\/node .*native-server\.ts --serve/)
  assert.match(unit,/ProtectHome=yes/)
  assert.match(unit,/ProtectSystem=strict/)
  assert.match(unit,/NoNewPrivileges=yes/)
  assert.match(unit,/IPAddressDeny=any/)
  assert.match(unit,/IPAddressAllow=127\.0\.0\.0\/8/)
  assert.doesNotMatch(unit,/^\[Install\]/m)
  assert.doesNotMatch(unit,/\b(?:User=root|Environment=.*DATABASE_URL|Environment=.*PASSWORD=[^$%])/)
})
test("LAN HTTPS audit is only read-only diagnostics and leaves services untouched",()=>{
  assert.match(audit,/set -euo pipefail/)
  assert.match(audit,/192\[.\]168\[.\]1\[.\]133/)
  assert.match(audit,/ss -H -ltn/)
  assert.match(audit,/BAOTA_NGINX_VHOST_CONF_FILES/)
  assert.match(audit,/READ_ONLY=TRUE/)
  assert.match(audit,/NO_PORT_OPENED=TRUE/)
  assert.match(audit,/NO_SERVICE_RESTARTED=TRUE/)
  assert.doesNotMatch(audit,/\b(?:systemctl\s+(?:restart|start|stop)|nginx\s+-s|ufw\s+allow|iptables\s+-[AI]|openssl\s+req|rm\s+-rf)\b/i)
})
test("minimal portal is HTTPS fail-closed, does not persist credentials or inject HTML",()=>{
  assert.match(portal,/location\.protocol!=="https:"/)
  assert.match(portal,/if\(location\.protocol!=="https:"\)throw Error\("https_required"\)/)
  assert.match(portal,/credentials:"same-origin"/)
  assert.match(portal,/X-AgentStudio-Request/)
  assert.match(portal,/textContent/)
  assert.match(portal,/\/api\/native-auth\/logout/)
  assert.match(portal,/\/api\/native-auth\/me/)
  assert.match(portal,/\/api\/native-auth\/login/)
  assert.match(portal,/\/api\/v2\/agent-specs/)
  assert.doesNotMatch(portal,/\b(?:localStorage|sessionStorage|document\.cookie|innerHTML|eval|Function\(|XMLHttpRequest|console\.)\b/)
  assert.doesNotMatch(portal,/\/api\/native-auth\/employees|\/api\/v2\/runs|\/__pb\//)
  assert.match(html,/<script defer src="\/app\.js"><\/script>/)
  assert.match(html,/<link rel="stylesheet" href="\/style\.css">/)
  assert.doesNotMatch(html,/<script(?![^>]*src=)[^>]*>[\s\S]*?<\/script>/i)
  assert.doesNotMatch(html,/\b(?:http:|https:\/\/cdn|unpkg\.com|jsdelivr\.net)\b/)
})
